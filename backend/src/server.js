import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import { prisma } from './db.js';
import authRoutes from './routes/auth.js';
import productRoutes from './routes/products.js';
import orderRoutes from './routes/orders.js';
import adminRoutes from './routes/admin.js';
const app=express();
app.use(cors({origin:process.env.CLIENT_URL?.split(',')||'http://localhost:5173'}));
app.use(express.json({limit:'2mb'}));
app.get('/health',(req,res)=>res.json({status:'ok',service:'NovaTech API'}));
app.use('/api/auth',authRoutes); app.use('/api/products',productRoutes); app.use('/api/orders',orderRoutes); app.use('/api/admin',adminRoutes);
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:'Lỗi máy chủ. Vui lòng thử lại.'})});
const port=Number(process.env.PORT)||8000;
app.listen(port,()=>console.log(`NovaTech API running at http://localhost:${port}`));
process.on('SIGINT',async()=>{await prisma.$disconnect();process.exit(0)});
